"""Package a built project into a standalone executable.

ADM's build stage produces app.py (a module of functions verified by tests). To make it runnable,
this generates a small command-line entry point that exposes those functions, then uses PyInstaller
to produce a one-file executable. PyInstaller needs a full Python environment; the bundled embeddable
runtime cannot run it, so packaging looks for a Python that has PyInstaller and reports clearly when
none is available (a future update will bundle one).
"""
from __future__ import annotations
import os
import re
import shutil
import subprocess
from pathlib import Path
from .engine import SafetyError

ENTRY = '''"""Command-line entry point generated by ADM. Runs the functions your program provides."""
import inspect
import sys
import app

TITLE = __ADM_TITLE__
EXE = __ADM_EXE__


def _functions():
    return {name: fn for name, fn in inspect.getmembers(app, inspect.isfunction)
            if not name.startswith("_") and getattr(fn, "__module__", None) == "app"}


def _convert(value):
    for cast in (int, float):
        try:
            return cast(value)
        except ValueError:
            pass
    return value


def main(argv):
    functions = _functions()
    print(TITLE)
    if not functions:
        print("This program has no commands yet.")
        return 0
    if not argv or argv[0] in ("-h", "--help", "help"):
        print("Commands:")
        for name, fn in functions.items():
            params = " ".join("<%s>" % p for p in inspect.signature(fn).parameters)
            print("  %s %s" % (name, params))
        print("\\nExample:  %s %s ..." % (EXE, next(iter(functions))))
        return 0
    name = argv[0]
    if name not in functions:
        print("Unknown command: %s (run with --help)" % name)
        return 2
    args = [_convert(a) for a in argv[1:]]
    try:
        result = functions[name](*args)
    except TypeError as exc:
        print("Wrong number or type of values for %s: %s" % (name, exc))
        return 2
    except Exception as exc:
        print("Error: %s" % exc)
        return 1
    print(result)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
'''


def exe_name(title: str) -> str:
    base = re.sub(r'[^A-Za-z0-9]+', '-', str(title)).strip('-').lower()
    return (base or 'app')[:40]


def plan_title(plan) -> str:
    """Read a human title from a plan of any shape, defensively.

    A plan may be malformed (not a dict, or 'content' missing or not a dict).
    Never raise; fall back to a safe default. Control characters (including
    null bytes and newlines) are stripped so the title is safe to embed.
    """
    content = plan.get('content') if isinstance(plan, dict) else None
    raw = content.get('title') if isinstance(content, dict) else None
    title = str(raw) if raw not in (None, '') else 'My Program'
    cleaned = ''.join(ch for ch in title if ch >= ' ' and ch != '\x7f')
    cleaned = ' '.join(cleaned.split())          # collapse any whitespace runs
    return (cleaned or 'My Program')[:60]


def write_entry(root, plan) -> Path:
    """Write main.py (if absent) that exposes app's functions on the command line."""
    root = Path(root)
    title = plan_title(plan)
    name = exe_name(title)
    entry = root / 'main.py'
    if not entry.is_file():
        # Inject as repr() so backslashes, quotes, and unicode can never break
        # the generated source. EXE first (its slug is alnum/hyphen only, so it
        # can't contain the title token), then TITLE.
        content = ENTRY.replace('__ADM_EXE__', repr(name)).replace('__ADM_TITLE__', repr(title))
        with open(entry, 'w', encoding='utf-8', newline='') as stream:
            stream.write(content)
    return entry


def _python_candidates() -> list:
    found = []
    for name in ('python3', 'python'):
        which = shutil.which(name)
        if which:
            found.append(which)
    return found


def find_packager_python(candidates=None):
    """A Python interpreter that can run PyInstaller, or None."""
    for py in (candidates if candidates is not None else _python_candidates()):
        try:
            if subprocess.run([py, '-c', 'import PyInstaller'], capture_output=True, timeout=30).returncode == 0:
                return py
        except (OSError, subprocess.SubprocessError):
            continue
    return None


def package_command(python: str, entry: Path, name: str, dist_dir: Path, build_dir: Path) -> list:
    return [python, '-m', 'PyInstaller', '--noconfirm', '--clean', '--onefile', '--console',
            '--name', name, '--distpath', str(dist_dir),
            '--workpath', str(build_dir / 'work'), '--specpath', str(build_dir), str(entry)]


def package_project(root, dist_dir, *, plan: dict, python=None, timeout=1200) -> dict:
    """Generate the entry point and build a one-file executable. Requires PyInstaller."""
    root = Path(root).resolve()
    if not (root / 'app.py').is_file():
        raise SafetyError('There is no built program (app.py) to package')
    entry = write_entry(root, plan)
    py = python or find_packager_python()
    if not py:
        raise SafetyError('Packaging needs Python with PyInstaller, which is not available yet on this PC.')
    name = exe_name(plan_title(plan))
    dist_dir = Path(dist_dir)
    dist_dir.mkdir(parents=True, exist_ok=True)
    build_dir = root / '.adm-build'
    cmd = package_command(py, entry, name, dist_dir, build_dir)
    try:
        proc = subprocess.run(cmd, cwd=str(root), capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return {'status': 'failed', 'exe': None, 'name': name, 'reason': 'Packaging timed out'}
    exe = dist_dir / (name + ('.exe' if os.name == 'nt' else ''))
    ok = proc.returncode == 0 and exe.is_file()
    return {'status': 'packaged' if ok else 'failed', 'exe': str(exe) if ok else None, 'name': name,
            'returncode': proc.returncode,
            'output_tail': ((proc.stdout or '')[-2000:] + '\n' + (proc.stderr or '')[-2000:])}
